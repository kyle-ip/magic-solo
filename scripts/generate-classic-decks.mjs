function cleanList(list) {
  return list
    .filter((row) => row && typeof row === 'object' && row.name && row.qty > 0)
    .map(({ name, qty, board }) => ({ name, qty, board: board || 'main' }))
}

function cleanDeck(d) {
  return {
    ...d,
    keyCards: d.keyCards.filter(Boolean),
    sampleList: cleanList(d.sampleList),
  }
}

// Fix accidental garbage in generator data
for (const d of NEW) {
  d.sampleList = cleanList(d.sampleList)
  // Fix Black Lotus qty typo if string
  for (const row of d.sampleList) {
    if (typeof row.qty === 'string') row.qty = Number(row.qty) || 1
  }
}

const allFiles = fs.readdirSync(outDir).filter((f) => f.endsWith('.json') && f !== 'index.json')
const kept = allFiles.map((f) => {
  const id = f.replace(/\.json$/, '')
  return JSON.parse(fs.readFileSync(path.join(outDir, f), 'utf8'))
})

const byId = new Map(kept.map((d) => [d.id, d]))
for (const d of NEW) {
  if (byId.has(d.id)) continue
  const cleaned = cleanDeck(d)
  byId.set(cleaned.id, cleaned)
  fs.writeFileSync(path.join(outDir, `${cleaned.id}.json`), JSON.stringify(cleaned, null, 2) + '\n')
  console.log('wrote', cleaned.id)
}

const index = {
  decks: [...byId.values()].map((d) => ({
    id: d.id,
    format: d.format,
    name: d.name,
    colors: d.colors,
    playstyle: d.playstyle,
    era: d.era,
    coverCard: d.coverCard,
  })),
}

// Stable-ish order: format then name
const formatOrder = ['modern', 'legacy', 'pioneer', 'pauper', 'vintage', 'standard-classic']
index.decks.sort((a, b) => {
  const fa = formatOrder.indexOf(a.format)
  const fb = formatOrder.indexOf(b.format)
  if (fa !== fb) return fa - fb
  return a.name.en.localeCompare(b.name.en)
})

fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 2) + '\n')
console.log('index decks:', index.decks.length)
